import { notFound } from "next/navigation";
import { one, all, type Block, type Claim, type Segment, type AuditEvent } from "@/lib/db";
import { getSession } from "@/lib/auth";
import { renderSegments } from "@/lib/rules";
import { fmtDate } from "@/lib/util";

export const dynamic = "force-dynamic";

export default function Evidence({ params }: { params: { id: string } }) {
  const s = getSession()!;
  const b = one<Block>("SELECT * FROM blocks WHERE id=? AND org_id=?", params.id, s.org);
  if (!b) notFound();
  const segments = JSON.parse(b.segments) as Segment[];
  const claims = all<Claim>("SELECT * FROM claims WHERE org_id=?", s.org);
  const byId = new Map(claims.map((c) => [c.id, c]));
  const usedClaims = segments.filter((x): x is Extract<Segment, { type: "claim" }> => x.type === "claim")
    .map((x) => byId.get(x.claimId)).filter(Boolean) as Claim[];
  const events = all<AuditEvent>(
    `SELECT * FROM audit_events WHERE org_id=? AND (
       (entity_type='block' AND entity_id=?) OR
       (entity_type='claim' AND entity_id IN (${usedClaims.map(() => "?").join(",") || "''"}))
     ) ORDER BY id`,
    s.org, b.id, ...usedClaims.map((c) => c.id)
  );

  return (
    <div className="mx-auto max-w-3xl bg-white p-8 print:p-0">
      <div className="no-print mb-4 flex justify-end">
        <button className="btn" onClick={undefined} form="none" type="button" data-print>
          {/* print button via plain anchor below to keep this a server component */}
        </button>
      </div>
      <h1 className="font-serif text-2xl font-bold text-navy">Evidence Packet</h1>
      <p className="mb-6 text-sm text-navy/60">Generated by Canonly · {fmtDate(new Date().toISOString())} · Block ID {b.id}</p>

      <h2 className="font-serif text-lg font-bold text-navy">1. Published content</h2>
      <p className="mb-1 text-sm font-semibold">{b.question}</p>
      <p className="mb-6 rounded border border-navy/10 p-3 text-sm">{renderSegments(segments, byId)}</p>

      <h2 className="font-serif text-lg font-bold text-navy">2. Claims used, with substantiation</h2>
      {usedClaims.map((c) => (
        <div key={c.id} className="mb-3 rounded border border-navy/10 p-3 text-sm">
          <b>{c.title}</b> — status: {c.status}{c.expires_at ? ` · expires ${c.expires_at.slice(0, 10)}` : ""}
          <div className="mt-1">“{c.text}”</div>
          <div className="mt-1 text-navy/60">Substantiation: {c.substantiation_note ?? "—"} {c.substantiation_url ? `(${c.substantiation_url})` : ""}</div>
        </div>
      ))}

      <h2 className="mt-6 font-serif text-lg font-bold text-navy">3. Complete audit trail</h2>
      <table className="w-full text-sm">
        <thead><tr className="border-b border-navy/20 text-left"><th className="py-1 pr-3">When</th><th className="py-1 pr-3">Actor</th><th className="py-1 pr-3">Action</th><th className="py-1">Entity</th></tr></thead>
        <tbody>
          {events.map((e) => (
            <tr key={e.id} className="border-b border-navy/5 align-top">
              <td className="py-1 pr-3 whitespace-nowrap">{fmtDate(e.created_at)}</td>
              <td className="py-1 pr-3">{e.actor_label}</td>
              <td className="py-1 pr-3">{e.action}</td>
              <td className="py-1 text-navy/60">{e.entity_type}:{e.entity_id.slice(0, 10)}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="mt-6 text-xs text-navy/50">
        Audit events are append-only. Print this page (⌘P) to produce a PDF for a regulator or internal counsel.
      </p>
    </div>
  );
}
